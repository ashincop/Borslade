#define PORT 0x3f8 // COM1

int init_serial()
{
	outb(PORT + 1, 0x00); // Disable all interrupts
	outb(PORT + 3, 0x80); // Enable DLAB (set baud rate divisor)
	outb(PORT + 0, 0x03); // Set divisor to 3 (lo byte) 38400 baud
	outb(PORT + 1, 0x00); //                  (hi byte)
	outb(PORT + 3, 0x03); // 8 bits, no parity, one stop bit
	outb(PORT + 2, 0xC7); // Enable FIFO, clear them, with 14-byte threshold
	outb(PORT + 4, 0x0B); // IRQs enabled, RTS/DSR set
	outb(PORT + 4, 0x1E); // Set in loopback mode, test the serial chip
	outb(PORT + 0, 0xAE); // Test serial chip (send byte 0xAE and check if
			      // serial returns same byte)

	// Check if serial is faulty (i.e: not same byte as sent)
	if (inb(PORT + 0) != 0xAE) {
		return 1;
	}

	// If serial is not faulty set it in normal operation mode
	// (not-loopback with IRQs enabled and OUT#1 and OUT#2 bits enabled)
	outb(PORT + 4, 0x0F);
	return 0;
}
static int is_transmit_empty() { return inb(PORT + 5) & 0x20; }

void write_serial(char a)
{
	while (!is_transmit_empty())
		;
	outb(PORT, a);
}
void write_serial_string(const char *str)
{
	while (*str) {
		write_serial(*str++);
	}
}
// Helper to print a string at current tx, ty
void kprint_s(const char *s)
{
	for (int i = 0; s[i] != '\0'; i++) {
		// 1. Handle Newline
		if (s[i] == '\n') {
			tx = 10;
			ty += 16;

			if (ty >= 720)
				scroll_up(); // Check scroll here
			continue;
		}

		// 2. Handle Wrapping
		if (tx > 1200) { // Using 1200 as a safe right margin
			tx = 10;
			ty += 16;

			if (ty >= 720)
				scroll_up(); // Check scroll here
		}

		// 3. Draw the character
		draw_char(s[i], tx, ty, fg_color);
		tx += 8;
	}
}
// Helper to convert int/hex to string
void kprint_n(uint64_t n, int base)
{
	char buf[64];
	char *t = "0123456789ABCDEF";
	int i = 0;
	if (n == 0) {
		kprint_s("0");
		return;
	}
	while (n > 0) {
		buf[i++] = t[n % base];
		n /= base;
	}
	while (--i >= 0) {
		char s[2] = {buf[i], 0};
		kprint_s(s);
	}
}
void write_serial_n(uint64_t n, int base)
{
	char buf[64];
	char *t = "0123456789ABCDEF";
	int i = 0;
	if (n == 0) {
		write_serial_string("0");
		return;
	}
	while (n > 0) {
		buf[i++] = t[n % base];
		n /= base;
	}
	while (--i >= 0) {
		char s[2] = {buf[i], 0};
		write_serial_string(s);
	}
}
void clear_screen(uint32_t color)
{
	// 1. Get the base address of the framebuffer
	uint32_t *fb_ptr = (uint32_t *)fb->addr;

	// 2. Calculate the total number of pixels on the screen
	// We use pitch / 4 to account for any padding at the end of scanlines
	uint32_t pixels_per_line = fb->pitch / 4;
	uint32_t total_pixels = pixels_per_line * fb->height;

	// 3. Fill the memory with the color (0x00000000 for black)
	for (uint32_t i = 0; i < total_pixels; i++) {
		fb_ptr[i] = color;
	}
	tx = 10;
	ty = 10;
}

