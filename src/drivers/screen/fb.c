void draw_pixel(int x, int y, uint32_t color)
{
	struct multiboot_tag_framebuffer *fb_info = (void *)fb;
	uint32_t *fb_ptr = (uint32_t *)fb_info->addr;
	uint32_t pixels_per_line = fb_info->pitch / 4;
	fb_ptr[y * pixels_per_line + x] = color;
}
void draw_rect(int x, int y, int width, int height, uint32_t color)
{
	struct multiboot_tag_framebuffer *fb_info = (void *)fb;
	uint32_t *fb_ptr = (uint32_t *)fb_info->addr;

	// Pitch is usually in bytes, so we divide by 4 to get 'pixels per line'
	uint32_t pixels_per_line = fb_info->pitch / 4;

	for (int curr_y = y; curr_y < y + height; curr_y++) {
		for (int curr_x = x; curr_x < x + width; curr_x++) {
			// Formula: Base + (Y * LineLength) + X
			fb_ptr[curr_y * pixels_per_line + curr_x] = color;
		}
	}
}
void scroll_up()
{
	// USE THE HARDWARE PITCH - DO NOT CALCULATE IT MANUALLY
	uint32_t pitch = fb->pitch;
	uint8_t *fb_ptr = (uint8_t *)fb->addr;

	// We want to move rows 16-719 up to 0-703
	uint32_t rows_to_copy = 720 - 16;
	size_t bytes_to_copy = (size_t)rows_to_copy * pitch;
	size_t offset_bytes = (size_t)16 * pitch;

	// 1. FORWARD COPY: Because dest < src, forward copy is safe and won't
	// corrupt. We use a simple loop or a forward-only memcpy to be 100%
	// sure.
	uint64_t *dest = (uint64_t *)fb_ptr;
	uint64_t *src = (uint64_t *)(fb_ptr + offset_bytes);

	// Move memory in 8-byte chunks for speed and stability
	for (size_t i = 0; i < (bytes_to_copy / 8); i++) {
		dest[i] = src[i];
	}

	// 2. CLEAR THE BOTTOM: Use the same pitch to ensure no "trailing"
	// artifacts
	uint64_t *bottom = (uint64_t *)(fb_ptr + bytes_to_copy);
	for (size_t i = 0; i < (offset_bytes / 8); i++) {
		bottom[i] = 0;
	}

	// 3. Update cursor
	ty = 720 - 16;
}
void draw_char(char c, int x, int y, uint32_t fg)
{
	// 1. Map the char to the font array (cast to unsigned to avoid negative
	// indices) font8x16[char_index] gives us the 16 bytes for that
	// character
	unsigned char *glyph = font8x16[(unsigned char)c];

	// 2. Setup framebuffer pointers
	uint32_t *fb_ptr = (uint32_t *)fb->addr;
	uint32_t pitch = fb->pitch / 4; // Convert byte-pitch to pixel-pitch

	// 3. Draw 16 rows
	for (int row = 0; row < 16; row++) {
		// Get the byte representing the 8 pixels in this row
		unsigned char data = glyph[row];

		// Calculate the exact starting pixel in the framebuffer for
		// this row
		uint32_t *line = fb_ptr + (y + row) * pitch + x;

		// 4. Draw the 8 bits (pixels) from Left to Right
		// 0x80 is 10000000 in binary (the leftmost pixel)
		if (data & 0x80)
			line[0] = fg;
		if (data & 0x40)
			line[1] = fg;
		if (data & 0x20)
			line[2] = fg;
		if (data & 0x10)
			line[3] = fg;
		if (data & 0x08)
			line[4] = fg;
		if (data & 0x04)
			line[5] = fg;
		if (data & 0x02)
			line[6] = fg;
		if (data & 0x01)
			line[7] = fg;
	}
}
