#include <stdarg.h>

// Terminal state
int tx = 10; 
int ty = 10;
uint32_t fg_color = 0xFFFFFFFF; // White
void draw_char(char c, int x, int y, uint32_t fg) {
    // If the char is not in our array, just draw a space
    const uint8_t *glyph = font_vga_8x16[(uint8_t)c];
    
    // Safety check for your framebuffer pointer
    uint32_t *fb_ptr = (uint32_t *)fb->addr; 
    uint32_t pitch = fb->pitch / 4;

    for (int row = 0; row < 16; row++) {
        for (int col = 0; col < 8; col++) {
            // Check the bit at the current column (7 is the leftmost bit)
            if (glyph[row] & (0x80 >> col)) {
                fb_ptr[(y + row) * pitch + (x + col)] = fg;
            }
        }
    }
}
// Helper to print a string at current tx, ty
void kprint_s(const char* s) {
    for (int i = 0; s[i] != '\0'; i++) {
        if (s[i] == '\n') {
            tx = 10;
            ty += 16;
            continue;
        }
        draw_char(s[i], tx, ty, fg_color);
        tx += 8;
        // Simple wrap
        if (tx > 800) { tx = 10; ty += 16; }
    }
}

// Helper to convert int/hex to string
void kprint_n(uint64_t n, int base) {
    char buf[64];
    char *t = "0123456789ABCDEF";
    int i = 0;
    if (n == 0) { kprint_s("0"); return; }
    while (n > 0) {
        buf[i++] = t[n % base];
        n /= base;
    }
    while (--i >= 0) {
        char s[2] = {buf[i], 0};
        kprint_s(s);
    }
}

void kprintf(const char* fmt, ...) {
    va_list args;
    va_start(args, fmt);

    for (const char* p = fmt; *p != '\0'; p++) {
        if (*p != '%') {
            char s[2] = {*p, 0};
            kprint_s(s);
            continue;
        }

        p++; // Skip '%'
        switch (*p) {
            case 's': kprint_s(va_arg(args, char*)); break;
            case 'd': kprint_n(va_arg(args, uint64_t), 10); break;
            case 'x': kprint_s("0x"); kprint_n(va_arg(args, uint64_t), 16); break;
            case 'c': {
                char s[2] = {(char)va_arg(args, int), 0};
                kprint_s(s);
                break;
            }
            case 'f': // "Focusing on F" - Floating point is tricky in kernels
                kprint_s("[FLOAT_NOT_IMPL]"); 
                break;
            default: kprint_s("?"); break;
        }
    }
    va_end(args);
}
void init_gop(uint64_t mbi_addr) {
    struct multiboot_tag *tag;

    // The first 8 bytes of MBI are total size and a reserved field
    for (tag = (struct multiboot_tag *)(mbi_addr + 8); 
         tag->type != 0; 
         tag = (struct multiboot_tag *)((uint8_t *)tag + ((tag->size + 7) & ~7))) {
        
        if (tag->type == 8) { // Framebuffer info
            fb = (void *)tag;
            kprintf("GOP has been initialized!\n");
        }
    }
}