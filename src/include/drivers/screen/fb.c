#include "fb.h"
struct multiboot_tag_framebuffer *fb;

void draw_rect(int x, int y, int width, int height, uint32_t color) {
    struct multiboot_tag_framebuffer *fb_info = (void *)fb;
    uint32_t *fb_ptr = (uint32_t *)fb_info->addr;

    // Pitch is usually in bytes, so we divide by 4 to get 'pixels per line'
    uint32_t pixels_per_line = fb_info->pitch / 4;

    for (int curr_y = y; curr_y < y + height; curr_y++) {
        for (int curr_x = x; curr_x < x + width; curr_x++) {
            // Formula: Base + (Y * LineLength) + X
            fb_ptr[curr_y * pixels_per_line + curr_x] = color;
        }
    }
}

